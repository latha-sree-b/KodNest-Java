public class sumUsingOperators {
    public static void main(String[] args) {
        // Define two integer variables with values 10 and 20 respectively.
        int a=10;
        int b=20;

        // Use the addition operator to calculate the sum of 'a' and 'b'.
        int result=a+b;

        // Print the sum of 'a' and 'b' to the console.
        System.out.println("sum of a and b is "+result);
    }
}
