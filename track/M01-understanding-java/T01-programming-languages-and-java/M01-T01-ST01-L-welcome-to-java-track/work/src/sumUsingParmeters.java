public class sumUsingParmeters {
    public static void main(String[] args) {
        // Declare and initialize two integer variables.
        int a = 10;
        int b = 20;
        // Call the sum method with 'a' and 'b' as arguments.
        sum(a, b);
    }

    // Define a method 'sum' that accepts two integers 'a' and 'b' as parameters.
    public static void sum(int a, int b) {
        // Print the sum of 'a' and 'b'.
        System.out.println(a+b);
    }

}
